"""Run the MLPerf Tiny integer programs (tiny/qnet.py) on the multiplierless Ibex (Verilator).

For every (dataset, model, seed, precision, method): generate the network as C (net.h), build hw/sw/tiny.c
with the method's dot product, simulate the first N test inputs in small batches, and check every logit
against the bit-exact Python reference (tiny.qnet.int_forward). Methods:
  exact, dn1, dn2   fused multiply-accumulate with the routine from csrc/roba_core.h (needs LOD for dn1/dn2)
  sqtab             exact products from a table of squares (no LOD)
  sqapx             approximate squares via LOD (negative result; int8 only)

  python3 hw/run_tiny.py --dataset cifar10 --model resnet8 --seeds 0 --bits 8 --images 20 --jobs 40
outputs results/tiny/<dataset>/<model>_ibex_{images,summary}.csv
"""
import argparse
import concurrent.futures as cf
import csv
import hashlib
import pathlib
import sys
import time

import torch

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "hw"))

import run_ibex as ri  # noqa: E402
from tiny import data as D  # noqa: E402
from tiny import qnet as Q  # noqa: E402

HW = ROOT / "hw"
FUSED = {"exact": "roba_exact_nz", "dn1": "roba_dn1_nz", "dn2": "roba_dn2_nz"}
P_LOD, P_NONE = 0.829, 0.793                # core power relative to a single-cycle-multiplier core (paper)


def log(*a):
    print(time.strftime("[%H:%M:%S]"), *a, flush=True)


def defines(method):
    if method == "sqtab":
        return ["SQTAB"]
    if method == "sqapx":
        return ["SQAPX"]
    return [f"MULT_NZ={FUSED[method]}"]


# ---------------------------------------------------------------- C generation

def arr(ctype, name, values, const=True):
    return ri.c_array(ctype, name, [int(v) for v in values]).replace("static const", "static const" if const
                                                                    else "static")


def write_net_h(path, prog):
    bits = prog["bits"]
    ops = prog["ops"]
    signed = prog.get("input") == "signed"
    numel = lambda s: s[0] * s[1] * s[2]
    pad_max = pads_max = pos_max = 1
    for op in ops:
        if op["op"] == "conv":
            c, h, w = op["shape_in"]
            ph, pw = Q.pad2(op["pad"])
            hp, wp = h + 2 * ph, w + 2 * pw
            if ph or pw:
                if signed and op["src"] == "in":
                    pads_max = max(pads_max, hp * wp * c)
                else:
                    pad_max = max(pad_max, hp * wp * c)
            pos_max = max(pos_max, hp * wp * (c if op.get("groups", 1) > 1 else 1))
    wt = "int16_t" if bits == 16 else "int8_t"
    out = [f"/* generated by hw/run_tiny.py: {prog['method']} int{bits} */\n",
           f"#define BITS {bits}\n#define QA {Q.QA[bits]}\n#define QW {Q.QW[bits]}\n",
           f"#define PAD_MAX {pad_max}\n#define PADS_MAX {pads_max}\n#define POS_MAX {pos_max}\n",
           f"#define N_OPS {len(ops)}\n#define N_OUT {numel(ops[-1]['shape_out'])}\n",
           f"#define IN_SIZE {numel(ops[0]['shape_in'])}\n",
           '#include "tiny_kernels.h"\n',
           f"typedef {'sin_t' if signed else 'act_t'} in_t;\n\n"]
    for op in ops:
        n = numel(op["shape_out"])
        if op.get("relu") == "logits":
            out.append(f"static int64_t LOGITS[{n}];\n")
        elif op.get("relu", True) is None:
            out.append(f"static acc_t B_{op['dst']}[{n}];\n")
        else:
            out.append(f"static act_t B_{op['dst']}[{n}];\n")
    init, fwd = [], []
    buf = lambda name: "x" if name == "in" else f"B_{name}"
    for i, op in enumerate(ops):
        if op["op"] == "avgpool":
            c, h, w = op["shape_in"]
            kh, kw = Q.k2(op["k"])
            fwd.append(f"    avgpool({buf(op['src'])}, {h}, {w}, {c}, {kh}, {kw}, {op['M']}, {op['SH']}, "
                       f"{buf(op['dst'])});\n")
        else:
            wq = op["wq"]
            o, cg, kh, kw = wq.shape
            c, h, w = op["shape_in"]
            g = op.get("groups", 1)
            assert g in (1, c) and (g == 1 or o == c), f"{op['name']}: only full and depthwise convs"
            K = kh * kw * cg
            # converted in place at startup (wk_t has the size of wq_t): one copy of the weights in RAM
            out.append(arr(wt, f"W{i}", wq.permute(0, 2, 3, 1).flatten(), const=False))
            out.append(f"#define WK{i} ((wk_t *)W{i})\n")
            out.append(f"#if defined(TABLE_METHOD)\nstatic int32_t SW{i}[{o}];\n#define SWP{i} SW{i}\n#else\n"
                       f"#define SWP{i} 0\n#endif\n")
            init.append(f"    prep_weights(W{i}, {o}, {K}, WK{i}, SWP{i});\n")
            _, oh, ow = op["shape_out"]
            ph, pw = Q.pad2(op["pad"])
            acc_out = op["relu"] is None
            if not acc_out:
                out += [arr("int32_t", f"M{i}", op["M"]), arr("int64_t", f"C{i}", op["C"]),
                        arr("uint8_t", f"SH{i}", op["SH"])]
                if op["skip"] is not None:
                    out.append(arr("int64_t", f"MS{i}", op["MS"]))
            sk = op["skip"]
            args = [buf(op["src"]), int(signed and op["src"] == "in"), h, w, c, o, kh, kw, op["stride"], ph, pw,
                    int(g > 1), oh, ow, f"WK{i}", f"SWP{i}",
                    "0" if acc_out else f"M{i}", "0" if acc_out else f"C{i}", "0" if acc_out else f"SH{i}",
                    f"MS{i}" if sk is not None else "0",
                    buf(sk["src"]) if sk is not None and sk["kind"] == "identity" else "0",
                    buf(sk["src"]) if sk is not None and sk["kind"] == "acc" else "0",
                    buf(op["dst"]) if acc_out else "0",
                    "0" if acc_out or op["relu"] == "logits" else buf(op["dst"]),
                    "LOGITS" if op["relu"] == "logits" else "0"]
            fwd.append(f"    conv({', '.join(str(a) for a in args)});\n")
        fwd.append(f"    u = (uint32_t)cycles(); lc[{i}] = u - t; t = u;\n")
    out.append("\nstatic void net_init(void)\n{\n" + "".join(init) + "}\n\n")
    out.append("static void forward(const void *x, uint32_t *lc)\n{\n    uint32_t t = (uint32_t)cycles(), u;\n"
               + "".join(fwd) + "}\n")
    path.write_text("".join(out))


def write_images_h(path, xq, labels, indices):
    n = xq.shape[0]
    hwc = xq.permute(0, 2, 3, 1).reshape(n, -1)
    parts = [f"/* generated by hw/run_tiny.py */\n#define N_IMG {n}\n",
             f"static const in_t IMG[N_IMG][IN_SIZE] = {{\n"]
    parts += ["  {" + ", ".join(str(int(v)) for v in img) + "},\n" for img in hwc]
    parts.append("};\n")
    parts.append(ri.c_array("uint8_t", "LABEL", labels))
    parts.append(ri.c_array("uint32_t", "IMG_INDEX", indices))
    path.write_text("".join(parts))


# ---------------------------------------------------------------- jobs

def configs(args):
    out = []
    for seed in args.seeds:
        for bits in args.bits:
            for method in args.methods:
                if Q.feasible(bits, method):
                    out.append((seed, bits, method))
    return out


def prepare(args):
    data = D.load(args.dataset, "cpu", val=5000)
    x, y = data["test"]
    # the autoencoder's test vectors come 309 per clip: take one from each of `images` clips
    pick = torch.arange(args.images) * (len(x) // args.images if data["task"] == "ae" else 1)
    x, y = x[pick], y[pick]
    args.task = data["task"]
    jobs, refs = [], {}
    ck = ROOT / "checkpoints" / "tiny" / args.dataset
    for seed, bits, method in configs(args):
        prog = torch.load(ck / f"{args.model}_s{seed}_int{bits}_{Q.TRAINED_WITH[method]}.pt", map_location="cpu",
                          weights_only=False)["prog"]
        z = Q.int_forward(prog, x, method)
        key = (args.dataset, args.model, f"s{seed}", f"int{bits}", method)
        refs[key] = {"pred": z.argmax(1).tolist(), "hash": [ri.logit_hash(r) for r in z]}
        gdir = HW / "gen" / "tiny" / "/".join(key)
        gdir.mkdir(parents=True, exist_ok=True)
        write_net_h(gdir / "net.h", prog)
        xq = Q.quantize_input(x, bits, prog)
        for b0 in range(0, args.images, args.batch):
            bdir = gdir / f"b{b0:05d}"
            bdir.mkdir(exist_ok=True)
            idx = list(range(b0, min(b0 + args.batch, args.images)))
            write_images_h(bdir / "images.h", xq[idx], y[idx].tolist(), idx)
            jobs.append({"key": key, "bdir": bdir, "elf": bdir / "tiny.elf", "method": method})
    return jobs, refs


def build(job):
    ri.compile_elf(HW / "sw" / "tiny.c", job["elf"], include_dirs=[job["bdir"], job["bdir"].parent],
                   defines=defines(job["method"]))


def run(job):
    run_dir = HW / "runs" / "tiny" / "/".join(job["key"]) / job["bdir"].name
    digest = hashlib.sha256(job["elf"].read_bytes()).hexdigest()
    log_file, sha_file = run_dir / "ibex_simple_system.log", run_dir / "elf.sha256"
    if (log_file.exists() and "DNN_DONE" in log_file.read_text()
            and sha_file.exists() and sha_file.read_text().strip() == digest):
        text, secs, speed = log_file.read_text(), 0.0, 0.0
    else:
        text, secs, speed = ri.run_sim(job["elf"], run_dir)
        if "DNN_DONE" not in text:
            raise RuntimeError(f"{job['bdir']}: simulation did not finish:\n{text[-500:]}")
        sha_file.write_text(digest)
    return job, [l for l in text.splitlines() if l.startswith("IMG,")], secs, speed


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dataset", default="cifar10")
    p.add_argument("--model", default="resnet8")
    p.add_argument("--seeds", nargs="+", type=int, default=[0])
    p.add_argument("--bits", nargs="+", type=int, default=list(Q.BITS))
    p.add_argument("--methods", nargs="+", default=list(Q.METHODS))
    p.add_argument("--images", type=int, default=20)
    p.add_argument("--batch", type=int, default=2)
    p.add_argument("--jobs", type=int, default=40)
    p.add_argument("--tag", default="", help="suffix of the output CSV names")
    args = p.parse_args()
    torch.set_num_threads(16)
    jobs, refs = prepare(args)
    log(f"compiling {len(jobs)} programs")
    with cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        list(ex.map(build, jobs))
    log(f"running {len(jobs)} simulations on {args.jobs} workers")
    rows, t0, done = [], time.time(), 0
    with cf.ThreadPoolExecutor(max_workers=args.jobs) as ex:
        for fut in cf.as_completed([ex.submit(run, j) for j in jobs]):
            job, lines, secs, speed = fut.result()
            ref = refs[job["key"]]
            for line in lines:
                f = line.split(",")
                i = int(f[1])
                rows.append({"dataset": job["key"][0], "model": job["key"][1], "seed": job["key"][2][1:],
                             "bits": job["key"][3][3:], "method": job["key"][4], "image": i, "label": int(f[2]),
                             "ibex_pred": int(f[3]), "ref_pred": ref["pred"][i],
                             "logits_match": int(f[4], 16) == ref["hash"][i], "cycles": int(f[5]),
                             **{f"op{l}_cycles": int(v) for l, v in enumerate(f[6:])}})
            done += 1
            log(f"{done}/{len(jobs)} batches ({time.time() - t0:.0f}s): {'/'.join(job['key'])}/{job['bdir'].name}"
                + (f" simulated in {secs:.0f}s at {speed / 1e3:.0f} kHz" if speed else " (reused)"))
    out = ROOT / "results" / "tiny" / args.dataset
    out.mkdir(parents=True, exist_ok=True)
    rows.sort(key=lambda r: (r["seed"], int(r["bits"]), Q.METHODS.index(r["method"]), r["image"]))
    ri.write_csv(out / f"{args.model}_ibex_images{args.tag}.csv", rows)
    summary = []
    for seed, bits, method in configs(args):
        rs = [r for r in rows if r["seed"] == str(seed) and r["bits"] == str(bits) and r["method"] == method]
        cyc = sum(r["cycles"] for r in rs) / len(rs)
        ops = sorted(k for k in rs[0] if k.startswith("op"))
        summary.append({"dataset": args.dataset, "model": args.model, "seed": seed, "bits": bits, "method": method,
                        "lod": int(method in ("dn1", "dn2", "sqapx")), "images": len(rs),
                        "ibex_acc": (sum(r["ibex_pred"] == r["label"] for r in rs) / len(rs)
                                     if args.task == "classify" else ""),
                        "logits_match_ref": sum(r["logits_match"] for r in rs) / len(rs),
                        "cycles_per_input": cyc,
                        **{k: sum(r[k] for r in rs) / len(rs) for k in ops}})
    for s in summary:
        base = next((t for t in summary if t["seed"] == s["seed"] and t["bits"] == s["bits"]
                     and t["method"] == "exact"), None)
        s["speedup_vs_exact"] = base["cycles_per_input"] / s["cycles_per_input"] if base else ""
        s["energy_vs_exact"] = (s["cycles_per_input"] * (P_LOD if s["lod"] else P_NONE)
                                / (base["cycles_per_input"] * P_NONE)) if base else ""
        log(f"s{s['seed']} int{s['bits']:<2} {s['method']:5s} logits match {s['logits_match_ref']:.3f} | "
            f"{s['cycles_per_input'] / 1e6:8.2f} M cycles | {s['speedup_vs_exact'] or 0:.2f}x | "
            f"energy {s['energy_vs_exact'] or 0:.2f}")
    ri.write_csv(out / f"{args.model}_ibex_summary{args.tag}.csv", summary)


if __name__ == "__main__":
    main()
